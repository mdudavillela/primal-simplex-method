def exemplo(numero):
  #1: ótimo (x = (3,1,,0,0,0), f = -11) | 2: ilimitado | 3: caso m == n
  if numero == 1:
    A = [[1, 1, 1, 0, 0],
         [1, 3, 0, 1, 0],
         [1, 0, 0, 0, 1]]
    b = [4, 6, 3]
    c = [-3, -2, 0, 0, 0]
    base = [2, 4, 3]
  elif numero == 2:
    A = [[1, -1, 1, 0],
         [-1, 1, 0, 1]]
    b =[1, 1]
    c = [-1, -1, 0, 0]
    base = [2, 3]
  else:
    A = [[1, 0],
         [0, 1]]
    b = [1, 2]
    c = [1, 1]
    base = [0, 1]
  return (np.array(A, dtype = float),
          np.array(b, dtype = float),
          np.array(c, dtype = float),
          base)

