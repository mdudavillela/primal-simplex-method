def le_vetor(texto, tamanho):
  #lê "tamanho" numeros separados por espaço (aceita virgula decimal)
  while True:
    partes = input(texto).replace(",", ".").split()
    try:
      vet = np.array([float(p) for p in partes])
    except ValueError:
      print("  Digite apenas números.")
      continue
    if len(vet) != tamanho:
      print(f"  Esperado {tamanho} valores, recebido {len(vet)}.")
      continue
    return vet

