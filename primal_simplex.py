def entrada():
  m = int(input("Digite o número de restrições: "))
  n = int(input("Digite o número de variáveis: "))
  if m > n:
    raise ValueError("Precisamos de restrições <= variáveis.")

  c = le_vetor(f"c ({n} valores): ", n)
  b = le_vetor(f"b ({m} valores): ", m)
  A = np.zeros((m, n))
  for i in range(m):
    A[i, :] = le_vetor(f"Linha {i + 1} de A ({n} valores): ", n)

  base = le_vetor(f"Base inicial ({m} índices de 1 a {n}): ", m)
  base = [int(j) - 1 for j in base] #1-based -> 0-based

  return A, b, c, base

