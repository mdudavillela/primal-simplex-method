def verifica_base_factivel(A, b, base):
  #verifica se a base informada pelo usuario é válida e factível
  m, n = A.shape
  if len(base) != m or len(set(base)) != m:
    raise ValueError(f"A base informada deve ter {m} índices distintos.")
  if any(j < 0 or j >= n for j in base):
    raise ValueError(f"Os índices da base devem estar entre 1 e {n}.")

  B = A[:, base]
  if abs(np.linalg.det(B)) < tolerancia:
    raise ValueError("A matriz informada não é invertível.")

  xB = np.linalg.solve(B, b)
  if np.any(xB < -tolerancia):
    raise ValueError(f"Base não factível: xB = {xB}")

