import numpy as np

tolerancia = 1e-9 #define o menor valor que o programa considera diferente de 0
max_iter = 1000 #número máximo de iterações pra evitar ciclagem

def fase2_simplex(A, b, c, base):
  #fase2_simplex: retorna (status, x, fx, it); status: ótimo ou ilimitado
  m, n = A.shape #m: linhas e n: colunas
  base = list(base)
  nao_base = [j for j in range(n) if j not in base] #lista c/ as colunas não base
  it = 0

  while it < max_iter:
    B = A[:, base] #B = todas as linhas de A, colunas da base
    N = A[:, nao_base] #N = todas as linhas de A, colonas da nao base (fora da base)
    cB = c[base] #coeficientes das variaveis basicas
    cN = c[nao_base] #coeficientes das variaveis nao basicas

    #PASSO 1: solução basica
    xB = np.linalg.solve(B, b)
    fx = cB @ xB
    x = np.zeros(n)
    x[base] = xB

    #caso m == n: não tem variavel não basica
    if len(nao_base) == 0:
      return "ótimo", x, fx, it

    #PASSO 2: custos relativos (das variaveis não basicas)
    lamb = np.linalg.solve(B.T, cB) #passo 2.1 - vetor multiplicador simplex
    cr = cN - N.T @ lamb #passo 2.2 - custos relativos
    cNk = np.argmin(cr) #passo 2.3 - escolha da variavel a entrar na base

    print("-" * 60) #linha pra separar as iterações
    print(f"Iteração {it}")
    print(f"Base: ", [i + 1 for i in base])
    print(f"Não base: ", [j + 1 for j in nao_base])
    print(f"xB: ", np.round(xB, 6))
    print(f"fx: ", round(fx, 6))
    print(f"λ: ", np.round(lamb, 6))
    print(f"Custos relativos: ", np.round(cr, 6))

    #PASSO 3: teste de otimalidade
    if cr[cNk] >= -tolerancia:
      print("custos relativos >= 0, então a solução é ótima")
      return "ótimo", x, fx, it

    #PASSO 4: direção simplex
    entra_na_base = nao_base[cNk]
    y = np.linalg.solve(B, A[:, entra_na_base])
    print(f"x{entra_na_base + 1} entra na base | y:", np.round(y, 6))

    if np.all(y <= tolerancia):
      print("y <= 0, então não existe solução ótima finita. Problema ilimitado.")
      return "ilimitado", None, None, it

    #PASSO 5: determinar passo e variavel a sair da base
    razoes = np.full(m, np.inf) #inf: infinito onde y <= 0 (não limita)
    pos = y > 0
    razoes[pos] = xB[pos] / y[pos]
    p = np.argmin(razoes) #posição do x q sai da base
    print(f"x{base[p] + 1} sai da base | passo = {razoes[p]:.6f}")

    #PASSO 6: atualização (nova partição báscia)
    base[p], nao_base[cNk] = nao_base[cNk], base[p]
    it = it + 1

  raise RuntimeError("Número máximo de iterações atingido.")

